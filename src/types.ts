export type UPIStatus = 'SUCCESS' | 'FAILURE' | 'SUBMITTED' | string;

export interface UPIPaymentConfig {
  /**
   * Virtual Payment Address (UPI ID) of the payee / merchant.
   * Example: 'merchant@upi' or 'merchant@okhdfcbank'
   */
  vpa: string;

  /**
   * Payee Name.
   * Example: 'Merchant Store' or 'John Doe'
   */
  name: string;

  /**
   * Transaction Amount formatted as decimal string.
   * Example: '1.00' or '250.50'
   */
  amount: string;

  /**
   * Unique Transaction Reference ID.
   * Example: 'TXN123456789'
   */
  txnRef: string;

  /**
   * Transaction Note or description.
   * Example: 'Payment for Order #101'
   */
  note?: string;

  /**
   * Currency code. Defaults to 'INR'.
   */
  currency?: string;

  /**
   * Merchant Category Code (MCC) for verified merchants.
   */
  merchantCode?: string;

  /**
   * Reference URL for the transaction.
   */
  url?: string;

  /**
   * Specific UPI app package name to launch directly, or 'CHOOSER' to show system chooser.
   * You can use values from `UPIApps` constants.
   * Defaults to Google Pay or Chooser if unspecified.
   */
  packageName?: string;

  /**
   * Transaction Mode (e.g. '00' for default, '02' for static/dynamic QR).
   */
  mode?: string;

  /**
   * Bank or Partner Org ID for verified merchant routing.
   */
  orgid?: string;
}

export interface UPIPaymentResponse {
  /**
   * Payment status ('SUCCESS', 'FAILURE', 'SUBMITTED', etc.)
   */
  status: UPIStatus;

  /**
   * Unique Transaction ID generated by the UPI payment gateway / app.
   */
  txnId?: string;

  /**
   * Transaction Reference ID passed in the request.
   */
  txnRef?: string;

  /**
   * Response code returned by the payment app / bank.
   * (e.g. '0' or '00' for success)
   */
  responseCode?: string;

  /**
   * Approval reference number from the bank.
   */
  approvalRefNo?: string;

  /**
   * Raw response string returned from the native Intent.
   * Example: 'txnId=UPI123&responseCode=0&ApprovalRefNo=987&Status=SUCCESS&txnRef=TXN01'
   */
  rawResponse: string;

  /**
   * Additional key-value pairs parsed from the response.
   */
  [key: string]: string | undefined;
}

export interface InstalledUPIApp {
  /**
   * Display name of the installed app (e.g. 'Google Pay', 'PhonePe')
   */
  name: string;

  /**
   * Android package name of the app (e.g. 'com.google.android.apps.nbu.paisa.user')
   */
  packageName: string;
}

export type UPIAppPackage =
  | 'com.google.android.apps.nbu.paisa.user'
  | 'com.phonepe.app'
  | 'net.one97.paytm'
  | 'in.org.npci.upiapp'
  | 'com.dreamplug.androidapp'
  | 'in.amazon.mShop.android.shopping'
  | 'CHOOSER'
  | (string & {});
